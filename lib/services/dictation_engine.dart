/// [v0.1.0] 听写引擎：生成中文同音/形近干扰项、英文拼写判定。
///
/// 三种听写模式：
/// - [DictationMode.charSelect]：听音选字，从 4 个选项中选正确字
/// - [DictationMode.spelling]：英文拼写，输入后自动判对错
/// - [DictationMode.voice]：语音跟读，复用 Vosk ASR 识别后判对错

/// 听写模式。
enum DictationMode {
  /// 中文听音选字（4 选 1）。
  charSelect('听音选字'),

  /// 英文拼写。
  spelling('拼写'),

  /// 语音跟读。
  voice('语音跟读');

  const DictationMode(this.label);
  final String label;
}

/// 一道听写题目。
class DictationQuestion {
  const DictationQuestion({
    required this.word,
    required this.lang,
    this.options,
  });

  /// 被考的词。
  final String word;

  /// 语言代码（zh/en）。
  final String lang;

  /// 选字模式的 4 个选项（正确项 + 3 干扰项，已打乱）。
  /// 拼写/语音模式下为 null。
  final List<String>? options;
}

/// 一次听写答案。
class DictationAnswer {
  const DictationAnswer({
    required this.question,
    required this.correct,
    this.input,
  });

  final DictationQuestion question;
  final bool correct;
  final String? input;
}

