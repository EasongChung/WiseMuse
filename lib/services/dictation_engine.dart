  /// 为中文词生成听音选字题目，返回 [DictationQuestion]。
  ///
  /// [word] 为单个中文字（如「大」），从同音字库取干扰项。
  /// 干扰项不足时从常用字补充，保证总有 4 个选项。
  static DictationQuestion makeCharSelectQuestion(String word) {
    final distractors = _homophones[word] ?? const <String>[];
    final options = <String>{word};
    options.addAll(distractors.take(3));

    // 不足 4 个时从常用字补充
    const commonChars =
        '的一是了不在有个人这上中大为来我到他天小们'
        '可出会时也对生子要就能下看过说起好把发以而学过如东'
        '西高长自作都然家成开得多心么十动方进种面后又分很但';
    while (options.length < 4) {
      options.add(commonChars[Random().nextInt(commonChars.length)]);
    }

    final shuffled = options.toList()..shuffle();
    return DictationQuestion(word: word, lang: 'zh', options: shuffled);
  }

  /// 为英文词生成拼写题目（无选项，仅记录原文）。
  static DictationQuestion makeSpellingQuestion(String word) {
    return DictationQuestion(word: word, lang: 'en');
  }

  /// 为语音跟读生成题目。
  static DictationQuestion makeVoiceQuestion(String word, String lang) {
    return DictationQuestion(word: word, lang: lang);
  }

  /// 检查听音选字答案。
  static bool checkCharSelect(String word, String selected) {
    return word == selected.trim();
  }

  /// 检查英文拼写（忽略大小写与首尾空白）。
  static bool checkSpelling(String word, String input) {
    return word.trim().toLowerCase() == input.trim().toLowerCase();
  }

  /// 从词列表生成听写题目。
  ///
  /// [words] 词列表，[mode] 听写模式，[count] 最多出题数。
  /// [v0.1.55] 选字模式若遇多字词，逐字拆分生成，保证词语亦可进入选字练习。
  static List<DictationQuestion> makeQuestions(
    List<String> words, {
    required DictationMode mode,
    int count = 10,
  }) {
    final questions = <DictationQuestion>[];
    for (final w in words) {
      if (questions.length >= count) break;
      switch (mode) {
        case DictationMode.charSelect:
          if (w.length == 1) {
            questions.add(makeCharSelectQuestion(w));
          } else {
            // 多字词逐字拆出单字生成题目
            for (var i = 0; i < w.length; i++) {
              if (questions.length >= count) break;
              final ch = w[i];
              if (RegExp(r'[一-龥]').hasMatch(ch)) {
                questions.add(makeCharSelectQuestion(ch));
              }
            }
          }
          break;
        case DictationMode.spelling:
          questions.add(makeSpellingQuestion(w));
          break;
        case DictationMode.voice:
          questions.add(makeVoiceQuestion(w, 'zh'));
          break;
      }
    }
    return questions;
  }
